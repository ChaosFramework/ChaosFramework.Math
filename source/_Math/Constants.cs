namespace ChaosFramework.Math
{
    public static class Constants
    {
        /// <summary> <see cref="System.Math.PI"/>. </summary>
        public const float PI = (float)System.Math.PI;

        /// <summary> <see cref="System.Math.PI"/> / 2.0. </summary>
        public const float PI_HALF = (float)(System.Math.PI / 2.0);

        /// <summary> <see cref="System.Math.PI"/> / 4.0. </summary>
        public const float PI_QUART = (float)(System.Math.PI / 4.0);

        /// <summary> <see cref="System.Math.PI"/> * 2.0. </summary>
        public const float PI_2 = (float)(System.Math.PI * 2.0);

        /// <summary> Square root of 2 </summary>
        public static readonly float SQRT2 = (float)System.Math.Sqrt(2);

        /// <summary> Base of the natural logarithm. </summary>
        public const float E = (float)System.Math.E;

        /// <summary> The natural logarithm of 2. </summary>
        public static readonly float LOG2 = (float)System.Math.Log(2);
    }
}
